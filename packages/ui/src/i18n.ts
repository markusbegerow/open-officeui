export type Key = keyof typeof de;
export const DICTS: Record<Lang, Record<Key, string>> = { de, en };

export function translate(lang: Lang, key: Key, vars: Record<string, string> = {}): string {
  return DICTS[lang][key].replace(/\{(\w+)\}/g, (m, name: string) => vars[name] ?? m);
}

export type T = (key: Key, vars?: Record<string, string>) => string;
export const makeT = (lang: Lang): T => (key, vars) => translate(lang, key, vars);
